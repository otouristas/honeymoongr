export const destinationsBySlug: Record<string, Destination> = Object.fromEntries(
  DESTINATIONS.map((d) => [d.slug, d]),
);

export function destinationsInRegion(region: Destination["region"]): Destination[] {
  return DESTINATIONS.filter((d) => d.region === region);
}

export function getDestination(slug: string): Destination | undefined {
  return destinationsBySlug[slug];
}

export function destinationNames(slugs: string[]): string[] {
  return slugs
    .map((slug) => destinationsBySlug[slug]?.name)
    .filter((name): name is string => Boolean(name));
}
